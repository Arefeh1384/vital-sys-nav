const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ts=require('typescript');
const source=fs.readFileSync(require('node:path').join(__dirname,'../dashboardStore.ts'),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const sites=[{id:'s1',name:'Site One'},{id:'s2',name:'Site Two'}];
const issues=[{id:'Q1',siteId:'s1',state:'open',severity:'critical'},{id:'Q2',siteId:'s1',state:'closed',severity:'critical'},{id:'Q3',siteId:'s2',state:'open',severity:'critical'}];
const risks=[{id:'R1',siteId:'s1'},{id:'R2',siteId:'s2'}];
const m={exports:{}};
const requireMock=(id)=>{
 if(id==='../data/mockData')return {SITES_DATA:sites};
 if(id==='../stewardship/store')return {listQualityIssues:()=>issues};
 if(id==='../supply/store')return {supplyRisks:risks,getCases:()=>[{riskId:'R1',status:'open'},{riskId:'R2',status:'closed'}]};
 throw Error('Unexpected dependency '+id);
};
vm.runInNewContext(code,{module:m,exports:m.exports,require:requireMock,Date,Math,Array,Object,JSON});
const api=m.exports;
assert.equal(api.calculateOccupancy(80,100),80);
assert.equal(api.calculateOccupancy(0,0),null);
assert.equal(api.weightedOccupancy([{occupied:80,staffed:100},{occupied:5,staffed:10}]),77.27);
const alerts=[{id:'a1',siteId:'s1',status:'new',severity:'critical'},{id:'a2',siteId:'s2',status:'new',severity:'critical'},{id:'a3',siteId:'s1',status:'resolved',severity:'critical'}];
const tasks=[{id:'t1',siteId:'s1',status:'open'},{id:'t2',siteId:'s1',status:'done'},{id:'t3',siteId:'s2',status:'open'}];
const a=api.getExecutiveDashboard('s1','day',alerts,tasks,new Date('2026-10-24T00:00:00Z'));
const value=(k)=>a.metrics.find(m=>m.key===k).value;
assert.equal(value('alerts'),1);assert.equal(value('criticalAlerts'),1);
assert.equal(value('tasks'),1);assert.equal(value('quality'),1);assert.equal(value('supply'),1);
assert.equal(a.issues.length,1);assert.equal(a.alerts.length,1);
assert.equal(api.getExecutiveDashboard('s2','day',alerts,tasks).metrics.find(m=>m.key==='quality').value,1);
assert.equal(a.metrics.find(m=>m.key==='occupancy').quality,'stale');
console.log('PASS dashboard mock aggregation, active-only counts, site isolation, denominator-zero, weighted occupancy');
